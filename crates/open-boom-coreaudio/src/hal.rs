//! CoreAudio HAL boundary and headless mock implementation.
//!
//! [`AudioHal`] is the seam between the OpenBoom macOS adapter and the operating
//! system audio stack. On macOS it is backed by the real CoreAudio HAL
//! (`AudioObject*` / `AudioDevice*` C APIs). Everywhere else — and in headless
//! tests on macOS — [`MockHal`] provides a deterministic, allocation-free-friendly
//! double whose IOProc callbacks can be driven frame-by-frame.
//!
//! The IOProc client-data handles created here point directly at the
//! [`SampleRing`] shared with capture/render clients, so audio actually flows
//! through the HAL boundary instead of being synthesized above it.

use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};

use open_boom_core::types::{AudioDeviceInfo, EngineError, EngineResult};

use crate::ring_buffer::SampleRing;

// CoreAudio's `AudioObject*` bindings reference Core Foundation helpers
// (`CFStringGetCString`, `CFRelease`). Link CoreFoundation explicitly so the symbols
// resolve when a final binary is produced; the `coreaudio-sys` build only links CoreAudio.
#[cfg(target_os = "macos")]
#[link(name = "CoreFoundation", kind = "framework")]
extern "C" {}

/// Configuration used to open a HAL capture or render stream.
#[derive(Debug, Clone)]
pub struct HalStreamConfig {
    /// Target device id, or `None` for the host default endpoint.
    pub device_id: Option<String>,
    /// Requested sample rate in Hertz.
    pub sample_rate: u32,
    /// Requested interleaved channel count.
    pub channels: u16,
    /// Requested buffer size in frames.
    pub buffer_frames: u32,
}

impl Default for HalStreamConfig {
    fn default() -> Self {
        Self {
            device_id: None,
            sample_rate: crate::DEFAULT_STREAM_RATE,
            channels: crate::DEFAULT_STEREO_CHANNELS,
            buffer_frames: crate::DEFAULT_BUFFER_FRAMES,
        }
    }
}

/// A running (or startable) HAL capture/render stream.
pub trait HalStream: Send {
    /// Starts the stream and begins invoking the IOProc.
    fn start(&mut self) -> EngineResult<()>;
    /// Stops the stream and detaches the IOProc.
    fn stop(&mut self) -> EngineResult<()>;
    /// Returns whether the stream is currently running.
    fn is_running(&self) -> bool;
    /// Negotiated sample rate in Hertz.
    fn sample_rate(&self) -> u32;
    /// Negotiated interleaved channel count.
    fn channels(&self) -> u16;
    /// Negotiated buffer size in frames.
    fn buffer_frames(&self) -> u32;
    /// Headless verification hook: runs the registered IOProc for `frames` frames
    /// exactly as CoreAudio would. Real, OS-driven streams return `Ok(0)`.
    fn drive_io_proc(&mut self, frames: usize) -> EngineResult<usize>;
}

/// The platform audio HAL boundary.
pub trait AudioHal: Send + Sync {
    /// Enumerates render-capable devices, with the current default flagged.
    fn enumerate_devices(&self) -> EngineResult<Vec<AudioDeviceInfo>>;
    /// Returns the current system default output device id.
    fn default_output_device_id(&self) -> EngineResult<Option<String>>;
    /// Returns the friendly name of a device, or `None` when it does not exist.
    fn device_name(&self, device_id: &str) -> EngineResult<Option<String>>;
    /// Sets the OS default output endpoint.
    fn set_default_output_device(&self, device_id: &str) -> EngineResult<()>;
    /// Opens a capture stream bound to `ring`, which the capture IOProc fills.
    fn open_capture(
        &self,
        config: HalStreamConfig,
        ring: Arc<SampleRing>,
    ) -> EngineResult<Box<dyn HalStream>>;
    /// Opens a render stream bound to `ring`, which the render IOProc drains.
    fn open_render(
        &self,
        config: HalStreamConfig,
        ring: Arc<SampleRing>,
    ) -> EngineResult<Box<dyn HalStream>>;
    /// Consumes and clears the "default output changed / device lost" edge.
    fn take_default_output_changed(&self) -> bool {
        false
    }
}

