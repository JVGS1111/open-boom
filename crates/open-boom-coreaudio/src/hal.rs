/// Default mock output device id.
pub const MOCK_DEFAULT_ID: &str = "mock_default";
/// Secondary mock output device id.
pub const MOCK_SPEAKERS_ID: &str = "mock_speakers";
/// Mock virtual sink device id (used by device-detection tests).
pub const MOCK_VIRTUAL_ID: &str = "mock_virtual";
/// Attributed friendly name for the mock virtual sink.
pub const MOCK_VIRTUAL_NAME: &str = "OpenBoom Spatial Audio (powered by BlackHole)";
/// Frequency of the synthetic verification tone generated by the forced-synthetic mock path.
pub const MOCK_TONE_HZ: f64 = 440.0;

/// Returns the deterministic device list exposed by [`MockHal`].
pub fn mock_devices(include_virtual: bool) -> Vec<AudioDeviceInfo> {
    let mut devices = vec![
        AudioDeviceInfo::new(MOCK_DEFAULT_ID, "Mock Speakers (Synthetic Audio)", true),
        AudioDeviceInfo::new(MOCK_SPEAKERS_ID, "Mock Headphones (Synthetic Audio)", false),
    ];
    if include_virtual {
        devices.push(AudioDeviceInfo::new(MOCK_VIRTUAL_ID, MOCK_VIRTUAL_NAME, false));
    }
    devices
}

#[derive(Default)]
struct MockHalState {
    capture_input: Mutex<VecDeque<f32>>,
    rendered: Mutex<Vec<f32>>,
    default_output: Mutex<Option<String>>,
    tone_enabled: bool,
    tone_phase: Mutex<f64>,
    default_changed: AtomicBool,
}

/// Deterministic, hardware-free [`AudioHal`] implementation.
///
/// Capture playback is either scripted by the test via [`MockHal::queue_capture_frames`]
/// or, on the explicit forced-synthetic path, generated as a 440 Hz tone. Rendered
/// samples are accumulated in an inspectable buffer so tests can assert exactly what
/// the render IOProc consumed.
#[derive(Clone)]
pub struct MockHal {
    state: Arc<MockHalState>,
    devices: Vec<AudioDeviceInfo>,
}

impl MockHal {
    /// Creates a mock HAL with default devices and no synthetic tone.
    pub fn new() -> Self {
        Self::with_options(false, false)
    }

    /// Creates a mock HAL, optionally exposing a virtual sink device.
    pub fn with_virtual(include_virtual: bool) -> Self {
        Self::with_options(include_virtual, false)
    }

    /// Creates a forced-synthetic mock HAL that generates a 440 Hz capture tone.
    pub fn with_tone(tone_enabled: bool) -> Self {
        Self::with_options(false, tone_enabled)
    }

    /// Creates a mock HAL with explicit virtual-device and synthetic-tone options.
    pub fn with_options(include_virtual: bool, tone_enabled: bool) -> Self {
        Self {
            state: Arc::new(MockHalState {
                tone_enabled,
                default_output: Mutex::new(Some(MOCK_DEFAULT_ID.to_string())),
                ..Default::default()
            }),
            devices: mock_devices(include_virtual),
        }
    }

    /// Queues interleaved Float32 samples to be delivered by the capture IOProc.
    pub fn queue_capture_frames(&self, samples: &[f32]) {
        if let Ok(mut input) = self.state.capture_input.lock() {
            input.extend(samples.iter().copied());
        }
    }

    /// Number of scripted capture samples not yet delivered.
    pub fn queued_capture_frames(&self) -> usize {
        self.state.capture_input.lock().map(|q| q.len()).unwrap_or(0)
    }

    /// Returns a snapshot of the interleaved samples consumed by the render IOProc.
    pub fn rendered_samples(&self) -> Vec<f32> {
        self.state.rendered.lock().map(|r| r.clone()).unwrap_or_default()
    }

    /// Takes and clears the samples consumed by the render IOProc.
    pub fn take_rendered_samples(&self) -> Vec<f32> {
        self.state
            .rendered
            .lock()
            .map(|mut r| std::mem::take(&mut *r))
            .unwrap_or_default()
    }

    /// Signals a simulated default-output change / device loss edge.
    pub fn mark_default_output_changed(&self) {
        self.state.default_changed.store(true, Ordering::SeqCst);
    }

    fn has_device(&self, device_id: &str) -> bool {
        self.devices.iter().any(|d| d.id == device_id)
    }

    fn current_default(&self) -> Option<String> {
        self.state
            .default_output
            .lock()
            .ok()
            .and_then(|guard| guard.clone())
    }
}

impl Default for MockHal {
    fn default() -> Self {
        Self::new()
    }
}

impl AudioHal for MockHal {
    fn enumerate_devices(&self) -> EngineResult<Vec<AudioDeviceInfo>> {
        let default = self.current_default();
        Ok(self
            .devices
            .iter()
            .map(|d| {
                let mut device = d.clone();
                device.is_default = Some(device.id.clone()) == default;
                device
            })
            .collect())
    }

    fn default_output_device_id(&self) -> EngineResult<Option<String>> {
        Ok(self.current_default())
    }

    fn device_name(&self, device_id: &str) -> EngineResult<Option<String>> {
        Ok(self
            .devices
            .iter()
            .find(|d| d.id == device_id)
            .map(|d| d.name.clone()))
    }

    fn set_default_output_device(&self, device_id: &str) -> EngineResult<()> {
        if !self.has_device(device_id) {
            return Err(EngineError::DeviceInitialization(format!(
                "unknown mock audio device: {device_id}"
            )));
        }
        if let Ok(mut default) = self.state.default_output.lock() {
            *default = Some(device_id.to_string());
        }
        self.state.default_changed.store(true, Ordering::SeqCst);
        Ok(())
    }

    fn open_capture(
        &self,
        config: HalStreamConfig,
        ring: Arc<SampleRing>,
    ) -> EngineResult<Box<dyn HalStream>> {
        if let Some(ref id) = config.device_id {
            if !self.has_device(id) {
                return Err(EngineError::DeviceInitialization(format!(
                    "unknown mock capture device: {id}"
                )));
            }
        }
        Ok(Box::new(MockCaptureStream {
            state: self.state.clone(),
            ring,
            sample_rate: config.sample_rate.max(1),
            channels: config.channels.max(1),
            buffer_frames: config.buffer_frames.max(1),
            running: false,
            scratch: Vec::new(),
        }))
    }

    fn open_render(
        &self,
        config: HalStreamConfig,
        ring: Arc<SampleRing>,
    ) -> EngineResult<Box<dyn HalStream>> {
        if let Some(ref id) = config.device_id {
            if !self.has_device(id) {
                return Err(EngineError::DeviceInitialization(format!(
                    "unknown mock render device: {id}"
                )));
            }
        }
        Ok(Box::new(MockRenderStream {
            state: self.state.clone(),
            ring,
            sample_rate: config.sample_rate.max(1),
            channels: config.channels.max(1),
            buffer_frames: config.buffer_frames.max(1),
            running: false,
            scratch: Vec::new(),
        }))
    }

    fn take_default_output_changed(&self) -> bool {
        self.state.default_changed.swap(false, Ordering::SeqCst)
    }
}

struct MockCaptureStream {
    state: Arc<MockHalState>,
    ring: Arc<SampleRing>,
    sample_rate: u32,
    channels: u16,
    buffer_frames: u32,
    running: bool,
    scratch: Vec<f32>,
}

impl HalStream for MockCaptureStream {
    fn start(&mut self) -> EngineResult<()> {
        self.running = true;
        Ok(())
    }

    fn stop(&mut self) -> EngineResult<()> {
        self.running = false;
        Ok(())
    }

    fn is_running(&self) -> bool {
        self.running
    }

    fn sample_rate(&self) -> u32 {
        self.sample_rate
    }

    fn channels(&self) -> u16 {
        self.channels
    }

    fn buffer_frames(&self) -> u32 {
        self.buffer_frames
    }

    fn drive_io_proc(&mut self, frames: usize) -> EngineResult<usize> {
        if !self.running {
            return Ok(0);
        }

        let channels = self.channels as usize;
        let total = frames * channels;
        self.scratch.clear();
        self.scratch.resize(total, 0.0);

        if self.state.tone_enabled {
            // Explicit forced-synthetic path only: deterministic 440 Hz tone.
            let mut phase = self.state.tone_phase.lock().map(|g| *g).unwrap_or(0.0);
            for frame in 0..frames {
                let value = (2.0 * std::f64::consts::PI * MOCK_TONE_HZ * phase
                    / self.sample_rate as f64)
                    .sin() as f32;
                for channel in 0..channels {
                    self.scratch[frame * channels + channel] = value;
                }
                phase += 1.0;
            }
            phase %= self.sample_rate as f64;
            if let Ok(mut stored) = self.state.tone_phase.lock() {
                *stored = phase;
            }
        } else if let Ok(mut input) = self.state.capture_input.lock() {
            let take = total.min(input.len());
            for slot in self.scratch.iter_mut().take(take) {
                *slot = input.pop_front().unwrap_or(0.0);
            }
        }

        let written = self.ring.push_frames(&self.scratch, channels);
        Ok(written)
    }
}

struct MockRenderStream {
    state: Arc<MockHalState>,
    ring: Arc<SampleRing>,
    sample_rate: u32,
    channels: u16,
    buffer_frames: u32,
    running: bool,
    scratch: Vec<f32>,
}

impl HalStream for MockRenderStream {
    fn start(&mut self) -> EngineResult<()> {
        self.running = true;
        Ok(())
    }

    fn stop(&mut self) -> EngineResult<()> {
        self.running = false;
        Ok(())
    }

    fn is_running(&self) -> bool {
        self.running
    }

    fn sample_rate(&self) -> u32 {
        self.sample_rate
    }

    fn channels(&self) -> u16 {
        self.channels
    }

    fn buffer_frames(&self) -> u32 {
        self.buffer_frames
    }

    fn drive_io_proc(&mut self, frames: usize) -> EngineResult<usize> {
        if !self.running {
            return Ok(0);
        }

        let channels = self.channels as usize;
        let total = frames * channels;
        self.scratch.clear();
        self.scratch.resize(total, 0.0);

        let read = self.ring.pop_frames(&mut self.scratch, channels) * channels;
        if let Ok(mut rendered) = self.state.rendered.lock() {
            rendered.extend_from_slice(&self.scratch[..read]);
        }
        Ok(read / channels)
    }
}

