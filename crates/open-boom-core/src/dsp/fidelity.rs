//! Fidelity psychoacoustic harmonic exciter and high-frequency clarity enhancer.
//!
//! Generates subtle 2nd and 3rd harmonic overtones and high-shelf air
//! specifically in the upper-frequency spectrum (> 3.2 kHz) to restore presence
//! and sparkle in compressed audio streams with 0.0ms latency and zero allocations
//! (FR17, NFR1, NFR2, NFR9).

use crate::types::INTERNAL_SAMPLE_RATE_F32;

/// Second-order high-pass filter to isolate upper harmonics band.
#[derive(Clone, Copy)]
struct HighPassBiquad {
    b0: f32,
    b1: f32,
    b2: f32,
    a1: f32,
    a2: f32,
    s1: f32,
    s2: f32,
}

impl HighPassBiquad {
    fn new(sample_rate: f32, cutoff_hz: f32) -> Self {
        let mut hp = Self {
            b0: 1.0,
            b1: 0.0,
            b2: 0.0,
            a1: 0.0,
            a2: 0.0,
            s1: 0.0,
            s2: 0.0,
        };
        hp.update(sample_rate, cutoff_hz);
        hp
    }

    fn update(&mut self, sample_rate: f32, cutoff_hz: f32) {
        let sr = if sample_rate <= 0.0 { INTERNAL_SAMPLE_RATE_F32 } else { sample_rate };
        let omega = 2.0 * std::f32::consts::PI * cutoff_hz.clamp(100.0, sr * 0.45) / sr;
        let (sin_w, cos_w) = omega.sin_cos();
        let alpha = sin_w / (2.0 * 0.70710678);

        let a0 = 1.0 + alpha;
        self.b0 = ((1.0 + cos_w) * 0.5) / a0;
        self.b1 = (-(1.0 + cos_w)) / a0;
        self.b2 = ((1.0 + cos_w) * 0.5) / a0;
        self.a1 = (-2.0 * cos_w) / a0;
        self.a2 = (1.0 - alpha) / a0;
    }

    #[inline]
    fn process(&mut self, x: f32) -> f32 {
        // Direct Form II Transposed
        let y = self.b0 * x + self.s1;
        self.s1 = self.b1 * x - self.a1 * y + self.s2;
        self.s2 = self.b2 * x - self.a2 * y;
        if y.is_finite() { y } else { 0.0 }
    }

    fn reset(&mut self) {
        self.s1 = 0.0;
        self.s2 = 0.0;
    }
}

/// DC-blocking high-pass filter (1-pole) to remove DC generated by quadratic terms.
#[derive(Clone, Copy)]
struct DcBlocker {
    x_prev: f32,
    y_prev: f32,
}

impl DcBlocker {
    const fn new() -> Self {
        Self {
            x_prev: 0.0,
            y_prev: 0.0,
        }
    }

    #[inline]
    fn process(&mut self, x: f32) -> f32 {
        // y[n] = x[n] - x[n-1] + R * y[n-1]
        let y = x - self.x_prev + 0.995 * self.y_prev;
        self.x_prev = x;
        self.y_prev = if y.is_finite() { y } else { 0.0 };
        self.y_prev
    }

    fn reset(&mut self) {
        self.x_prev = 0.0;
        self.y_prev = 0.0;
    }
}

/// Fidelity harmonic exciter module.
pub struct FidelityModule {
    pub enabled: bool,
    target_amount: f32,
    current_amount: f32,
    sample_rate: f32,
    // High-pass filters for L and R channels (> 3.2 kHz)
    hp_l: HighPassBiquad,
    hp_r: HighPassBiquad,
    // DC blockers for L and R
    dc_l: DcBlocker,
    dc_r: DcBlocker,
    // Air band 1-pole high-pass (> 7.5 kHz) for subtle upper-treble sparkle
    air_state_l: f32,
    air_state_r: f32,
}

impl Default for FidelityModule {
    fn default() -> Self {
        Self::new()
    }
}

impl FidelityModule {
    /// Creates a new Fidelity harmonic exciter module.
    pub fn new() -> Self {
        Self {
            enabled: false,
            target_amount: 0.45,
            current_amount: 0.0,
            sample_rate: INTERNAL_SAMPLE_RATE_F32,
            hp_l: HighPassBiquad::new(INTERNAL_SAMPLE_RATE_F32, 3200.0),
            hp_r: HighPassBiquad::new(INTERNAL_SAMPLE_RATE_F32, 3200.0),
            dc_l: DcBlocker::new(),
            dc_r: DcBlocker::new(),
            air_state_l: 0.0,
            air_state_r: 0.0,
        }
    }

    /// Sets the operational sample rate and updates filter coefficients.
    pub fn set_sample_rate(&mut self, sample_rate: f32) {
        self.sample_rate = sample_rate;
        self.hp_l.update(sample_rate, 3200.0);
        self.hp_r.update(sample_rate, 3200.0);
    }

    /// Sets the target exciter intensity (0.0 to 1.0).
    #[inline]
    pub fn set_amount(&mut self, amount: f32) {
        let safe = if amount.is_nan() || amount.is_infinite() {
            0.0
        } else {
            amount.clamp(0.0, 1.0)
        };
        self.target_amount = safe;
    }

    /// Returns the current target intensity.
    #[inline]
    pub fn amount(&self) -> f32 {
        self.target_amount
    }

    /// Processes a single stereo frame (left, right) with 0.0ms delay and zero heap allocations.
    #[inline]
    pub fn process_stereo(&mut self, left: f32, right: f32) -> (f32, f32) {
        if !self.enabled && self.current_amount <= 1e-4 {
            return (left, right);
        }

        // Smooth parameter interpolation towards target (~4ms ramp)
        let target = if self.enabled { self.target_amount } else { 0.0 };
        const SMOOTH_STEP: f32 = 0.005;
        if (self.current_amount - target).abs() < SMOOTH_STEP {
            self.current_amount = target;
        } else if self.current_amount < target {
            self.current_amount += SMOOTH_STEP;
        } else {
            self.current_amount -= SMOOTH_STEP;
        }

        if self.current_amount <= 1e-4 {
            return (left, right);
        }

        let l_in = if left.is_finite() { left } else { 0.0 };
        let r_in = if right.is_finite() { right } else { 0.0 };

        // 1. Isolate high-frequency energy above 3.2 kHz
        let hi_l = self.hp_l.process(l_in);
        let hi_r = self.hp_r.process(r_in);

        // 2. Synthesize 2nd (even) and 3rd (odd) harmonic overtones
        // 2nd harmonic: x^2 (asymmetric, warm presence) followed by DC blocker
        let h2_raw_l = hi_l * hi_l;
        let h2_raw_r = hi_r * hi_r;
        let h2_l = self.dc_l.process(h2_raw_l);
        let h2_r = self.dc_r.process(h2_raw_r);

        // 3rd harmonic: Chebyshev polynomial T3(x) = 4x^3 - 3x normalized,
        // or cubic saturation x - 0.33 x^3 for edge and vocal clarity
        let h3_l = hi_l.powi(3) * 0.75;
        let h3_r = hi_r.powi(3) * 0.75;

        // 3. Air shelf: gentle 1-pole high-pass (> 7.5 kHz) for upper-treble sparkle
        let air_alpha = 0.35; // pole at ~7.5 kHz
        self.air_state_l = (1.0 - air_alpha) * hi_l + air_alpha * self.air_state_l;
        self.air_state_r = (1.0 - air_alpha) * hi_r + air_alpha * self.air_state_r;
        let air_l = hi_l - self.air_state_l;
        let air_r = hi_r - self.air_state_r;

        // 4. Combine synthesized harmonics and air, soft-limiting to prevent harshness
        let harm_l = h2_l * 0.45 + h3_l * 0.30 + air_l * 0.35;
        let harm_r = h2_r * 0.45 + h3_r * 0.30 + air_r * 0.35;

        // Soft-saturation waveshaper: tanh-like soft clipping x / (1 + |x|)
        let sat_l = harm_l / (1.0 + harm_l.abs());
        let sat_r = harm_r / (1.0 + harm_r.abs());

        // 5. Blend into dry signal proportional to current_amount
        let mix_gain = self.current_amount * 0.35;
        let out_l = l_in + (sat_l * mix_gain);
        let out_r = r_in + (sat_r * mix_gain);

        (out_l, out_r)
    }

    /// Flushes all internal filter states to 0.0.
    pub fn reset(&mut self) {
        self.hp_l.reset();
        self.hp_r.reset();
        self.dc_l.reset();
        self.dc_r.reset();
        self.air_state_l = 0.0;
        self.air_state_r = 0.0;
        self.current_amount = 0.0;
    }
}
